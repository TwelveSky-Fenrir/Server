using System.Collections.Immutable;
using System.Linq;
using Fenrir.Generators.Analysis.Model;
using Fenrir.Generators.Analysis.Support;

namespace Fenrir.Generators.Protocol.Emitters;

/// <summary>
///     Emits <c>Fenrir.Contracts.Wire.SessionStateGate</c> (spec §5.4) from discovered
///     <c>[FenrirPacket(..., AllowedStates = [...])]</c>. Restricted to INCOMING packets: gating protects RECEIVING
///     a client opcode against an inconsistent session state — an outgoing packet never needs to be "allowed",
///     the server decides whether to send it.
/// </summary>
internal static class SessionStateGateEmitter
{
    public const string HintName = "SessionStateGate.g.cs";

    public static string Emit(ImmutableArray<TypeModel> packets)
    {
        var loginEntries = packets
            .Where(p => p.Server == FenrirServer.Login &&
                        p is { Direction: FenrirDirection.Incoming, AllowedStates.Length: > 0 })
            .OrderBy(p => p.Opcode)
            .ToImmutableArray();

        var zoneEntries = packets
            .Where(p => p.Server == FenrirServer.Zone &&
                        p is { Direction: FenrirDirection.Incoming, AllowedStates.Length: > 0 })
            .OrderBy(p => p.Opcode)
            .ToImmutableArray();

        var writer = new IndentedWriter();
        writer.Line("// <auto-generated/>");
        writer.Line("#nullable enable");
        writer.Line();
        writer.Line("namespace Fenrir.Contracts.Wire;");
        writer.Line();
        writer.Line("/// <summary>");
        writer.Line(
            "/// An opcode with no declared [FenrirPacket(AllowedStates = [...])] is legal in any session state");
        writer.Line("/// (e.g. handshake op 0): <c>Allows</c> then always returns <c>true</c> for that opcode.");
        writer.Line("/// </summary>");
        writer.Line("public static class SessionStateGate");
        writer.OpenBrace();

        EmitAllows(writer, "LoginSessionState", loginEntries);
        writer.Line();
        EmitAllows(writer, "ZoneSessionState", zoneEntries);

        writer.CloseBrace();
        return writer.ToString();
    }

    private static void EmitAllows(IndentedWriter writer, string stateEnum, ImmutableArray<TypeModel> entries)
    {
        writer.Line($"public static bool Allows({stateEnum} state, byte opcode)");
        writer.OpenBrace();
        writer.Line("return opcode switch");
        writer.OpenBrace();

        foreach (var packet in entries)
        {
            var condition = string.Join(" || ", packet.AllowedStates.Select(s => $"state == ({stateEnum}){s}"));
            writer.Line($"{packet.Opcode} => {condition},");
        }

        writer.Line("_ => true,");
        writer.CloseBraceSemicolon();
        writer.CloseBrace();
    }
}
